#!/usr/bin/env python3
"""Find flash that mods can reuse once log_printf is silenced.

The vendor code keeps its debug-log format strings next to the functions that print
them. modkit turns log_printf into a no-op when it packs mods into these strings, so
a block of strings is reusable when *every* use of every string in it is an argument
of a log_printf call. This script checks that against the decompiled code (strict:
a string with no visible use, or any use outside a log_printf line, rejects the
whole block) and writes reference/reclaim_arm.csv, which modkit reads.

    python tools/find_reclaimable.py
"""
import glob
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LOAD = 0x10003000
CODE_OFF, CODE_LEN = 0x1000, 0x1AA94
MIN_BLOCK = 16
# Blocks checked by hand that the strict text rule can't prove.
MANUAL = [
    (0x1001A14C, 0x1001A24C, "Switch Pro emulation logs; 'switch lights=%x' goes via a local "
                             "that is only passed to log_printf (sum_cmd, region_10018000.c)"),
]
STR_RUN = re.compile(rb"(?:[\x20-\x7e\r\n\t]{2,}\x00{1,4})+")
STR_ONE = re.compile(rb"([\x20-\x7e\r\n\t]{2,})\x00")


def c_escape(s):
    return s.replace("\\", "\\\\").replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t").replace('"', '\\"')


def main():
    img = open(os.path.join(ROOT, "firmware", "NS36_V3.4.bin"), "rb").read()
    code = img[CODE_OFF:CODE_OFF + CODE_LEN]
    lines = []
    for f in glob.glob(os.path.join(ROOT, "src", "arm", "decompiled", "region_*.c")):
        lines += open(f, encoding="utf-8", errors="ignore").read().splitlines()
    text_uses = {}

    def uses(st):
        if st not in text_uses:
            key = '"' + c_escape(st) + '"'
            text_uses[st] = [l for l in lines if key in l]
        return text_uses[st]

    blocks, total = [], 0
    # Runs of NUL-terminated printable strings, 4-byte padded (ARMCC layout). Code bytes
    # just before a run can look printable, so the first string may carry a junk prefix:
    # it's trimmed off until the rest is a string the decompiled code actually uses.
    for m in STR_RUN.finditer(code):
        base = LOAD + CODE_OFF + m.start()
        strs = [(base + x.start(1), x.group(1)) for x in STR_ONE.finditer(m.group())]
        if not strs:
            continue
        a0, first = strs[0]
        for j in range(min(8, len(first) - 1)):
            if uses(first[j:].decode("latin-1")):
                strs[0] = (a0 + j, first[j:])
                break
        # keep every stretch of consecutive log-only strings (a string used anywhere
        # else, or not visibly used at all, splits the run)
        run_end = LOAD + CODE_OFF + m.end()
        cur = None
        for idx, (sa, raw) in enumerate(strs):
            u = uses(raw.decode("latin-1"))
            good = bool(u) and all("log_printf(" in l for l in u)
            if good and cur is None:
                cur = (sa, raw)
            if not good or idx == len(strs) - 1:
                if cur is not None:
                    end = sa if not good else run_end
                    a, e = (cur[0] + 3) & ~3, end & ~3
                    if e - a >= MIN_BLOCK:
                        blocks.append((a, e, cur[1].decode("latin-1")))
                        total += e - a
                cur = None
    for a, e, why in MANUAL:
        if not any(x[0] <= a < x[1] or a <= x[0] < e for x in blocks):
            blocks.append((a, e, "[manual] " + why))
            total += e - a
    blocks.sort()
    out = os.path.join(ROOT, "reference", "reclaim_arm.csv")
    with open(out, "w", newline="\n") as f:
        f.write("# Flash blocks holding only log_printf format strings; reusable by mods when\n")
        f.write("# modkit silences log_printf. Generated by tools/find_reclaimable.py.\n")
        f.write("start,end,length\n")
        for a, e, _ in blocks:   # addresses only: no vendor text in the repository
            f.write(f"0x{a:08x},0x{e:08x},{e - a}\n")
    print(f"{len(blocks)} blocks, {total} bytes -> {out}")


if __name__ == "__main__":
    main()
