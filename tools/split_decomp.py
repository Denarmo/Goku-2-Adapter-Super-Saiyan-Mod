#!/usr/bin/env python3
"""Split a Ghidra decompiler dump into <outdir>/region_XXXXX.c files (8 KiB address buckets).

usage: split_decomp.py <dump.c> <outdir> <label>
"""
import os, re, sys

src, outd, label = sys.argv[1:4]
txt = open(src, encoding="utf-8", errors="replace").read()
buckets = {}
for p in re.split(r"(?m)^(?=/\* ==== )", txt):
    m = re.match(r"/\* ==== (\S+) @ (?:\w+:)?([0-9a-fA-F]+)", p)
    if m:
        buckets.setdefault(int(m.group(2), 16) & ~0x1FFF, []).append(p)
HDR = """/*
 * Goku 2 Adapter Super Saiyan Mod - decompiled reference source (%s)
 * Address range 0x%08X-0x%08X. Generated by tools/decompile.sh - do not hand-edit;
 * put names in reference/names_*.csv and regenerate instead.
 * Machine-generated pseudo-C: NOT directly compilable.
 */
#include "../../ghidra_types.h"

"""
os.makedirs(outd, exist_ok=True)
for f in os.listdir(outd):
    if f.startswith("region_") and f.endswith(".c"):
        os.remove(os.path.join(outd, f))
for b, ps in sorted(buckets.items()):
    with open(os.path.join(outd, "region_%08x.c" % b), "w", encoding="utf-8", newline="\n") as f:
        f.write(HDR % (label, b, b + 0x1FFF) + "".join(ps))
print(f"{label}: {len(buckets)} files, {sum(map(len, buckets.values()))} functions")
